function LegalPage({ title, children }: { title: string; children: ReactNode }) {
  useEffect(() => {
    const prev = document.title;
    document.title = `${title} | ${SITE.agentName}`;
    return () => {
      document.title = prev;
    };
  }, [title]);
  return (
    <article className="container legal">
      <h1>{title}</h1>
      <p className="legal__updated">עדכון אחרון: {SITE.legal.updated}</p>
      {children}
    </article>
  );
}

